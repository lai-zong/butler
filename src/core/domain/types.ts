/**
 * 领域标识。
 *
 * ⚠️ 从 v7 起它**不再表示"哪个仆人在干活"**，只表示"这件事属于哪个领域"。
 *    改名照旧（`life`/`health`/…）是为了**兼容已落盘的记忆数据** ——
 *    `MemoryEntry.domain` 里存的就是这些字符串，改名要迁移数据。
 */
export type DomainId = 'life' | 'health' | 'study' | 'work' | 'code';

/** 全部领域（顺序固定，用于稳定排序与遍历）。 */
export const DOMAIN_IDS: readonly DomainId[] = ['life', 'health', 'study', 'work', 'code'];

