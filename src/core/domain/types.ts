/** 领域的中文名（界面上用）。未知值原样返回，避免界面显示空白。 */
export function domainName(id: string): string {
  return (DOMAIN_INFO as Record<string, { name: string } | undefined>)[id]?.name ?? id;
}

/** 是不是合法领域标识。用于校验外部传入的数据。 */
export function isDomainId(v: unknown): v is DomainId {
  return typeof v === 'string' && (DOMAIN_IDS as readonly string[]).includes(v);
}

/**
 * 从一段文本里**粗判**它涉及哪些领域。
 *
 * ★ 这不是"路由" —— 旧架构的路由要用 LLM 判断"该派给谁"（已砍，D-3）。
 *   这个函数只做**打标签**，用途是：
 *     · 分层反思时按领域切分（创新点①）
 *     · 监督员决定要切哪几个领域视角
 *
 * ⚠️ 它是**启发式**，命中不了就返回空数组（表示"没判断出领域"），
 *    由调用方决定要不要追问或按通用方式处理。**不猜、不硬塞。**
 */
export function inferDomains(text: string): DomainId[] {
  const hits: DomainId[] = [];
  // ⚠️ 顺序必须与 `DOMAIN_IDS` 一致 —— 否则返回顺序不稳定，界面标签会乱跳
  const rules: { id: DomainId; re: RegExp }[] = [
    { id: 'life', re: /买菜|超市|餐厅|外卖|快递|出行|路线|租房|水电|家务|冰箱|食材|做饭|购物|预算/ },
    { id: 'health', re: /过敏|营养|减脂|增肌|热量|蛋白|脂肪|作息|运动|健身|睡眠|体重|血压|血糖|忌口/ },
    { id: 'study', re: /学习|复习|考试|课程|教程|练习|笔记|论文|读书|知识|背单词|刷题/ },
    { id: 'work', re: /文档|日程|会议|汇报|简历|PPT|表格|排期|项目进度|周报|邮件/ },
    { id: 'code', re: /代码|编程|调试|脚本|编译|报错|函数|接口|数据库|部署|git|Bug/i },
  ];
  for (const r of rules) {
    if (r.re.test(text)) hits.push(r.id);
  }
  return hits;
}
