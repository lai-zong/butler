/**
 * 领域标签 —— 「这属于哪个领域」
 *
 * ★★ 这个模块是「管家+仆人」→「管家+监督员」改造的产物（A1）。
 *
 * ═══ 为什么需要它 ═══
 *
 *   旧架构里有一个 `DomainId` 类型，但它被**两套语义复用**：
 *
 *     | 用在哪 | 实际含义 |
 *     |---|---|
 *     | 路由 / 派发 / 执行 | "哪个**执行者**在干活" |
 *     | 记忆 domain / 冲突 parties / 附件归属 | "这属于哪个**领域**" |
 *
 *   新架构下**没有多个执行者**（管家自己干），所以第一套语义消失；
 *   但第二套语义**仍然完全需要**：
 *     · 记忆要按领域打标签（分层反思的作用域）
 *     · 监督员要按领域视角复核（D-7 的"领域视角"）
 *     · 冲突检测要知道涉及哪些领域
 *     · 附件要路由到对应领域
 *
 *   **所以本模块做的是"语义澄清"，不是"新功能"** ——
 *   把 `DomainId` 从「执行者身份」降级为「领域标签」。
 *
 * ═══ 与旧架构的边界（重要）═══
 *
 *   ✅ **保留**：领域划分本身（生活/健康/学习/办公/代码）+ 每个领域的纪律
 *   ❌ **不保留**：领域 = 一个可派发的执行单元
 *
 *   ⚠️ 一处必须说清：**这五个领域不是「学科」，是「能力范畴」**。
 *      「想学英语」和「想学数学」都属于 `study` —— 能力没变，学科变了。
 */

